<#
.SYNOPSIS
  Install and enroll a Wazuh agent on Windows (run in an elevated PowerShell).

.NOTES
  Origin: [Documented] The project installed the agent from the official MSI using the command
  generated by the Wazuh dashboard ("Deploy new agent"). The exact command was not recorded;
  this script follows the standard format from the Wazuh documentation and is a [Recommendation].
  Verify the MSI URL/version for your Wazuh release.

.EXAMPLE
  .\install-agent.ps1 -Manager <manager address> -AgentName DC01 -Version 4.7.5
#>
param(
  [Parameter(Mandatory = $true)][string]$Manager,
  [string]$AgentName = $env:COMPUTERNAME,
  [string]$Version   = "4.7.5"
)
$ErrorActionPreference = "Stop"

$msi = Join-Path $env:TEMP "wazuh-agent.msi"
Invoke-WebRequest -Uri "https://packages.wazuh.com/4.x/windows/wazuh-agent-$Version-1.msi" -OutFile $msi

Start-Process msiexec.exe -Wait -ArgumentList @(
  "/i", "`"$msi`"", "/q",
  "WAZUH_MANAGER=$Manager",
  "WAZUH_AGENT_NAME=$AgentName"
)

Start-Service -Name "WazuhSvc"
Get-Service -Name "WazuhSvc"
Write-Host "Agent '$AgentName' installed. Confirm it is Active in the Wazuh dashboard."
